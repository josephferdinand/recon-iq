function generate(target) {
  const specPath = join(__root, target.spec);
  if (!existsSync(specPath)) throw new Error(`Missing spec: ${target.spec}`);
  const spec = parseYaml(readFileSync(specPath, "utf8"));
  const byTag = collectOps(spec);

  const outDir = join(__root, "sdks/typescript", target.version);
  if (existsSync(outDir)) rmSync(outDir, { recursive: true, force: true });
  mkdirSync(join(outDir, "src"), { recursive: true });

  writeFileSync(join(outDir, "src/index.ts"), renderIndex(spec, target.version, byTag));
  writeFileSync(join(outDir, "package.json"), renderPackageJson(target.version));
  writeFileSync(join(outDir, "tsconfig.json"), renderTsconfig());
  writeFileSync(join(outDir, "README.md"), renderReadme(target.version, byTag, spec));
  writeFileSync(join(outDir, "QUICKSTART.md"), renderQuickstart(target.version));

  const opCount = [...byTag.values()].reduce((n, o) => n + o.length, 0);
  return { version: target.version, tags: byTag.size, ops: opCount, outDir };
}

const results = TARGETS.map(generate);
for (const r of results) {
  console.log(`✔ ${r.version}  ${r.tags} tags · ${r.ops} operations  →  ${r.outDir.replace(__root + "/", "")}`);
}
