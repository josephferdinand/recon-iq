function renderTsconfig() {
  return JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "ES2022",
        moduleResolution: "bundler",
        declaration: true,
        strict: true,
        outDir: "dist",
        lib: ["ES2022", "DOM"],
        skipLibCheck: true,
      },
      include: ["src"],
    },
    null,
    2,
  ) + "\n";
}

