#!/usr/bin/env node
// Generate versioned TypeScript SDKs from OpenAPI specs.
//
// Reads:  docs/openapi/fvi-openapi.yaml         -> sdks/typescript/v4.0/
//         docs/openapi/fvi-openapi-v3.yaml      -> sdks/typescript/v3.0/
//
// Emits a lightweight fetch-based client with one method per operation, keyed
// by tag. No external runtime dependencies. Regenerated deterministically so
// diffs are reviewable in PRs.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const __root = resolve(fileURLToPath(import.meta.url), "../..");

const TARGETS = [
  { version: "v4.0", spec: "docs/openapi/fvi-openapi.yaml" },
  { version: "v3.0", spec: "docs/openapi/fvi-openapi-v3.yaml" },
];

const HEADER = `// AUTO-GENERATED by scripts/generate-sdk.mjs — do not edit by hand.
// Regenerate with:  npm run sdk:generate
`;

function camel(s) {
  return s.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()).replace(/^[A-Z]/, (m) => m.toLowerCase());
}
function pascal(s) {
  const c = camel(s);
  return c.charAt(0).toUpperCase() + c.slice(1);
}
function methodName(op, path, verb) {
  if (op.operationId) return camel(op.operationId);
  const parts = path
    .replace(/\{([^}]+)\}/g, "by_$1")
    .split("/")
    .filter(Boolean)
    .filter((p) => p !== "api");
  return camel([verb.toLowerCase(), ...parts].join("_"));
}

function collectOps(spec) {
  const byTag = new Map();
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const verb of ["get", "post", "put", "patch", "delete"]) {
      const op = item[verb];
      if (!op) continue;
      const tag = (op.tags && op.tags[0]) || "Default";
      if (!byTag.has(tag)) byTag.set(tag, []);
      byTag.get(tag).push({ path, verb, op });
    }
  }
  return byTag;
}

function renderMethod({ path, verb, op }) {
  const name = methodName(op, path, verb);
  const params = (op.parameters ?? []);
  const pathParams = params.filter((p) => p.in === "path");
  const queryParams = params.filter((p) => p.in === "query");
  const body = op.requestBody?.content?.["application/json"];

  const argFields = [];
  for (const p of pathParams) argFields.push(`${p.name}: string`);
  for (const p of queryParams) argFields.push(`${p.name}${p.required ? "" : "?"}: ${p.schema?.enum ? p.schema.enum.map((v) => JSON.stringify(v)).join(" | ") : "string | number | boolean"}`);
  if (body) argFields.push(`body: Record<string, unknown>`);

  const arg = argFields.length ? `args: { ${argFields.join("; ")} }` : "";
  const pathExpr = path.replace(/\{([^}]+)\}/g, (_, n) => `\${encodeURIComponent(args.${n})}`);

  const qLines = queryParams.length
    ? `    const q = new URLSearchParams();\n${queryParams
        .map((p) => `    if (args.${p.name} !== undefined) q.set(${JSON.stringify(p.name)}, String(args.${p.name}));`)
        .join("\n")}\n    const qs = q.toString(); const suffix = qs ? \`?\${qs}\` : "";\n`
    : "    const suffix = \"\";\n";

  const bodyExpr = body ? `JSON.stringify(args.body)` : "undefined";
  const summary = op.summary ? `\n  /** ${op.summary} */` : "";

  return `${summary}
  async ${name}(${arg}): Promise<unknown> {
${qLines}    return this.client.request({
      method: ${JSON.stringify(verb.toUpperCase())},
      path: \`${pathExpr}\${suffix}\`,
      body: ${bodyExpr},
    });
  }`;
}

function renderTagClass(tag, ops) {
  return `export class ${pascal(tag)}Api {
  constructor(private client: FviHttpClient) {}
${ops.map(renderMethod).join("\n")}
}
`;
}

function renderClient(spec, version, tags) {
  const serverUrl = (spec.servers?.[0]?.url) ?? "https://app-fvi.reconiq.example";
  return `${HEADER}
export interface FviClientOptions {
  /** Bearer token issued by Meta Cloud auth. */
  token: string;
  /** Optional base URL. Defaults to ${serverUrl}. */
  baseUrl?: string;
  /** Optional fetch implementation (defaults to global fetch). */
  fetchImpl?: typeof fetch;
  /** Optional per-request timeout in ms. */
  timeoutMs?: number;
  /** Extra headers merged into every request. */
  defaultHeaders?: Record<string, string>;
}

export class FviApiError extends Error {
  constructor(public status: number, public body: unknown, message: string) {
    super(message);
    this.name = "FviApiError";
  }
}

export class FviHttpClient {
  readonly baseUrl: string;
  readonly version = ${JSON.stringify(version)};
  private readonly token: string;
  private readonly fetchImpl: typeof fetch;
  private readonly timeoutMs?: number;
  private readonly defaultHeaders: Record<string, string>;

  constructor(opts: FviClientOptions) {
    if (!opts.token) throw new Error("FviClient: token is required");
    this.token = opts.token;
    this.baseUrl = (opts.baseUrl ?? ${JSON.stringify(serverUrl)}).replace(/\\/$/, "");
    this.fetchImpl = opts.fetchImpl ?? fetch;
    this.timeoutMs = opts.timeoutMs;
    this.defaultHeaders = opts.defaultHeaders ?? {};
  }

  async request({ method, path, body }: { method: string; path: string; body?: string }): Promise<unknown> {
    const ctrl = this.timeoutMs ? new AbortController() : undefined;
    const timer = ctrl && this.timeoutMs ? setTimeout(() => ctrl.abort(), this.timeoutMs) : undefined;
    try {
      const res = await this.fetchImpl(this.baseUrl + path, {
        method,
        headers: {
          "content-type": "application/json",
          "accept": "application/json",
          "authorization": \`Bearer \${this.token}\`,
          "x-fvi-sdk-version": this.version,
          ...this.defaultHeaders,
        },
        body,
        signal: ctrl?.signal,
      });
      const text = await res.text();
      const parsed = text ? safeJson(text) : null;
      if (!res.ok) {
        throw new FviApiError(res.status, parsed, \`FVI \${method} \${path} failed with \${res.status}\`);
      }
      return parsed;
    } finally {
      if (timer) clearTimeout(timer);
    }
  }
}

function safeJson(t: string): unknown {
  try { return JSON.parse(t); } catch { return t; }
}

export class FviClient {
${tags.map((t) => `  readonly ${camel(t)}: ${pascal(t)}Api;`).join("\n")}
  readonly http: FviHttpClient;
  constructor(opts: FviClientOptions) {
    this.http = new FviHttpClient(opts);
${tags.map((t) => `    this.${camel(t)} = new ${pascal(t)}Api(this.http);`).join("\n")}
  }
}
`;
}

function renderIndex(spec, version, byTag) {
  const tags = [...byTag.keys()];
  const classes = tags.map((t) => renderTagClass(t, byTag.get(t))).join("\n");
  return renderClient(spec, version, tags) + "\n" + classes;
}

